// Command codegen turns the three source-of-truth files in this repo into generated
// code, so that nothing downstream is ever hand-maintained:
//
//	backend/openapi.yaml  -> Go / Swift / Kotlin models + docs/API.md
//	content/microcopy.json -> typed copy-key constants + bundled resources
//	design/tokens.json     -> typed colour / spacing / type constants
//
// Run it from anywhere: `go run ./tools/codegen --root <repo>` (or `make generate`).
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "fail if any generated file is out of date instead of writing")
	flag.Parse()

	abs, err := filepath.Abs(*root)
	if err != nil {
		fail(err)
	}
	g := &generator{root: abs, check: *check}
	if err := g.run(); err != nil {
		fail(err)
	}
	if g.stale > 0 {
		fmt.Fprintf(os.Stderr, "codegen: %d generated file(s) out of date — run `make generate`\n", g.stale)
		os.Exit(1)
	}
	fmt.Printf("codegen: %d file(s) up to date\n", g.written)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "codegen:", err)
	os.Exit(1)
}

type generator struct {
	root    string
	check   bool
	written int
	stale   int
}

const banner = "// Code generated by tools/codegen from %s. DO NOT EDIT.\n"

func (g *generator) run() error {
	specPath := filepath.Join(g.root, "backend", "openapi.yaml")
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("parse openapi.yaml: %w", err)
	}
	spec, err := loadSpec(&doc)
	if err != nil {
		return err
	}
	if err := spec.validate(); err != nil {
		return err
	}

	copyKeys, err := loadCopyKeys(filepath.Join(g.root, "content", "microcopy.json"))
	if err != nil {
		return err
	}
	tokens, err := loadTokens(filepath.Join(g.root, "design", "tokens.json"))
	if err != nil {
		return err
	}

	outputs := []struct {
		path string
		body string
	}{
		{"backend/internal/api/models_gen.go", emitGoModels(spec)},
		{"ios/PodKit/Sources/PodAPI/Generated/Models.swift", emitSwiftModels(spec)},
		{"ios/PodKit/Sources/PodAPI/Generated/Copy.swift", emitSwiftCopy(copyKeys)},
		{"ios/PodKit/Sources/PodAPI/Generated/Tokens.swift", emitSwiftTokens(tokens)},
		{"android/core/api/src/main/kotlin/app/pod/api/generated/Models.kt", emitKotlinModels(spec)},
		{"android/core/api/src/main/kotlin/app/pod/api/generated/Copy.kt", emitKotlinCopy(copyKeys)},
		{"android/core/api/src/main/kotlin/app/pod/api/generated/Tokens.kt", emitKotlinTokens(tokens)},
		{"docs/API.md", emitAPIDocs(spec)},
	}
	for _, out := range outputs {
		body := out.body
		if strings.HasSuffix(out.path, ".go") {
			formatted, err := format.Source([]byte(body))
			if err != nil {
				return fmt.Errorf("%s: generated Go does not parse: %w", out.path, err)
			}
			body = string(formatted)
		}
		if err := g.write(out.path, body); err != nil {
			return err
		}
	}

	// The clients read microcopy at runtime, so each ships a byte-identical copy.
	microcopy, err := os.ReadFile(filepath.Join(g.root, "content", "microcopy.json"))
	if err != nil {
		return err
	}
	for _, dst := range []string{
		"ios/PodKit/Sources/PodAPI/Resources/microcopy.json",
		"android/core/api/src/main/res/raw/microcopy.json",
	} {
		if err := g.write(dst, string(microcopy)); err != nil {
			return err
		}
	}
	return nil
}

func (g *generator) write(rel, body string) error {
	path := filepath.Join(g.root, rel)
	if g.check {
		existing, err := os.ReadFile(path)
		if err != nil || string(existing) != body {
			fmt.Fprintf(os.Stderr, "  stale: %s\n", rel)
			g.stale++
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return err
	}
	g.written++
	return nil
}

// ---------------------------------------------------------------- yaml helpers

type entry struct {
	key string
	val *yaml.Node
}

// entries returns a mapping node's children in document order, which keeps generated
// output stable and readable rather than alphabetised.
func entries(n *yaml.Node) []entry {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	out := make([]entry, 0, len(n.Content)/2)
	for i := 0; i+1 < len(n.Content); i += 2 {
		out = append(out, entry{key: n.Content[i].Value, val: n.Content[i+1]})
	}
	return out
}

func child(n *yaml.Node, key string) *yaml.Node {
	for _, e := range entries(n) {
		if e.key == key {
			return e.val
		}
	}
	return nil
}

func text(n *yaml.Node, key string) string {
	c := child(n, key)
	if c == nil {
		return ""
	}
	return c.Value
}

func seq(n *yaml.Node) []*yaml.Node {
	if n == nil || n.Kind != yaml.SequenceNode {
		return nil
	}
	return n.Content
}

func strings_(n *yaml.Node) []string {
	out := make([]string, 0, len(seq(n)))
	for _, item := range seq(n) {
		out = append(out, item.Value)
	}
	return out
}

// ------------------------------------------------------------------ spec model

type Spec struct {
	Title        string
	Version      string
	Description  string
	Servers      []Server
	Tags         []Tag
	Schemas      []*Schema
	schemaByName map[string]*Schema
	Paths        []*Path
}

type Server struct{ URL, Description string }
type Tag struct{ Name, Description string }

type Path struct {
	Template   string
	Params     []*Param
	Operations []*Operation
}

type Operation struct {
	Method      string
	ID          string
	Summary     string
	Description string
	Tags        []string
	Milestone   string
	Public      bool // security: [] — no bearer token required
	Params      []*Param
	RequestBody string // schema ref name, "" if none
	Responses   []*Response
}

type Param struct {
	Name        string
	In          string
	Required    bool
	SchemaType  string
	Description string
}

type Response struct {
	Status      string
	Description string
	SchemaRef   string
}

type Schema struct {
	Name        string
	Description string
	Type        string
	Enum        []string
	Required    map[string]bool
	Props       []*Prop
	// scalar-only facets, carried through for documentation
	Format   string
	Min, Max string
}

type Prop struct {
	Name        string
	Description string
	Type        *TypeRef
	Required    bool
}

type TypeRef struct {
	Ref    string // component schema name
	Kind   string // string|integer|number|boolean|array|map
	Format string
	Enum   []string // inline enum
	Elem   *TypeRef // array element / map value
}

func loadSpec(doc *yaml.Node) (*Spec, error) {
	if len(doc.Content) == 0 {
		return nil, fmt.Errorf("empty document")
	}
	root := doc.Content[0]
	info := child(root, "info")
	s := &Spec{
		Title:        text(info, "title"),
		Version:      text(info, "version"),
		Description:  text(info, "description"),
		schemaByName: map[string]*Schema{},
	}
	for _, n := range seq(child(root, "servers")) {
		s.Servers = append(s.Servers, Server{URL: text(n, "url"), Description: text(n, "description")})
	}
	for _, n := range seq(child(root, "tags")) {
		s.Tags = append(s.Tags, Tag{Name: text(n, "name"), Description: text(n, "description")})
	}

	components := child(root, "components")
	sharedParams := child(components, "parameters")
	sharedResponses := child(components, "responses")

	for _, e := range entries(child(components, "schemas")) {
		sc := parseSchema(e.key, e.val)
		s.Schemas = append(s.Schemas, sc)
		s.schemaByName[e.key] = sc
	}

	for _, pe := range entries(child(root, "paths")) {
		p := &Path{Template: pe.key}
		for _, n := range seq(child(pe.val, "parameters")) {
			p.Params = append(p.Params, resolveParam(n, sharedParams))
		}
		for _, oe := range entries(pe.val) {
			method := strings.ToUpper(oe.key)
			switch method {
			case "GET", "POST", "PUT", "PATCH", "DELETE":
			default:
				continue
			}
			op := &Operation{
				Method:      method,
				ID:          text(oe.val, "operationId"),
				Summary:     text(oe.val, "summary"),
				Description: text(oe.val, "description"),
				Tags:        strings_(child(oe.val, "tags")),
				Milestone:   text(oe.val, "x-milestone"),
			}
			if sec := child(oe.val, "security"); sec != nil && len(seq(sec)) == 0 {
				op.Public = true
			}
			for _, n := range seq(child(oe.val, "parameters")) {
				op.Params = append(op.Params, resolveParam(n, sharedParams))
			}
			if rb := child(oe.val, "requestBody"); rb != nil {
				op.RequestBody = refName(text(schemaOf(rb), "$ref"))
			}
			for _, re := range entries(child(oe.val, "responses")) {
				resp := &Response{Status: re.key, Description: text(re.val, "description")}
				node := re.val
				if r := text(node, "$ref"); r != "" {
					node = child(sharedResponses, lastSegment(r))
					if resp.Description == "" {
						resp.Description = text(node, "description")
					}
				}
				resp.SchemaRef = refName(text(schemaOf(node), "$ref"))
				op.Responses = append(op.Responses, resp)
			}
			p.Operations = append(p.Operations, op)
		}
		s.Paths = append(s.Paths, p)
	}
	return s, nil
}

func schemaOf(node *yaml.Node) *yaml.Node {
	content := child(node, "content")
	for _, e := range entries(content) {
		_ = e
		return child(e.val, "schema")
	}
	return nil
}

func resolveParam(n *yaml.Node, shared *yaml.Node) *Param {
	if r := text(n, "$ref"); r != "" {
		n = child(shared, lastSegment(r))
	}
	sc := child(n, "schema")
	return &Param{
		Name:        text(n, "name"),
		In:          text(n, "in"),
		Required:    text(n, "required") == "true",
		SchemaType:  text(sc, "type"),
		Description: text(n, "description"),
	}
}

func parseSchema(name string, n *yaml.Node) *Schema {
	sc := &Schema{
		Name:        name,
		Description: text(n, "description"),
		Type:        text(n, "type"),
		Enum:        strings_(child(n, "enum")),
		Format:      text(n, "format"),
		Min:         text(n, "minimum"),
		Max:         text(n, "maximum"),
		Required:    map[string]bool{},
	}
	for _, r := range strings_(child(n, "required")) {
		sc.Required[r] = true
	}
	for _, e := range entries(child(n, "properties")) {
		sc.Props = append(sc.Props, &Prop{
			Name:        e.key,
			Description: text(e.val, "description"),
			Type:        parseTypeRef(e.val),
			Required:    sc.Required[e.key],
		})
	}
	return sc
}

func parseTypeRef(n *yaml.Node) *TypeRef {
	if r := text(n, "$ref"); r != "" {
		return &TypeRef{Ref: refName(r)}
	}
	t := text(n, "type")
	switch t {
	case "array":
		return &TypeRef{Kind: "array", Elem: parseTypeRef(child(n, "items"))}
	case "object":
		if ap := child(n, "additionalProperties"); ap != nil {
			return &TypeRef{Kind: "map", Elem: parseTypeRef(ap)}
		}
		return &TypeRef{Kind: "map", Elem: &TypeRef{Kind: "string"}}
	default:
		return &TypeRef{Kind: t, Format: text(n, "format"), Enum: strings_(child(n, "enum"))}
	}
}

func refName(ref string) string {
	if ref == "" {
		return ""
	}
	return lastSegment(ref)
}

func lastSegment(ref string) string {
	i := strings.LastIndex(ref, "/")
	return ref[i+1:]
}

// validate catches the mistakes that would otherwise surface as a broken client build,
// plus the product invariants from CLAUDE.md §2 that can be checked mechanically.
func (s *Spec) validate() error {
	var problems []string

	for _, sc := range s.Schemas {
		for _, p := range sc.Props {
			if err := checkTypeRef(s, sc.Name+"."+p.Name, p.Type); err != nil {
				problems = append(problems, err.Error())
			}
		}
		for r := range sc.Required {
			found := false
			for _, p := range sc.Props {
				if p.Name == r {
					found = true
				}
			}
			if !found {
				problems = append(problems, fmt.Sprintf("%s: required property %q has no definition", sc.Name, r))
			}
		}
	}

	seenOpIDs := map[string]string{}
	for _, p := range s.Paths {
		for _, op := range p.Operations {
			if op.ID == "" {
				problems = append(problems, fmt.Sprintf("%s %s: missing operationId", op.Method, p.Template))
				continue
			}
			if prev, ok := seenOpIDs[op.ID]; ok {
				problems = append(problems, fmt.Sprintf("operationId %q used by both %s and %s %s", op.ID, prev, op.Method, p.Template))
			}
			seenOpIDs[op.ID] = op.Method + " " + p.Template
			if op.Milestone == "" {
				problems = append(problems, fmt.Sprintf("%s: missing x-milestone", op.ID))
			}
			if op.RequestBody != "" && s.schemaByName[op.RequestBody] == nil {
				problems = append(problems, fmt.Sprintf("%s: request body references unknown schema %q", op.ID, op.RequestBody))
			}
			for _, r := range op.Responses {
				if r.SchemaRef != "" && s.schemaByName[r.SchemaRef] == nil {
					problems = append(problems, fmt.Sprintf("%s %s: unknown schema %q", op.ID, r.Status, r.SchemaRef))
				}
			}
		}
	}

	problems = append(problems, s.checkProductInvariants()...)

	if len(problems) > 0 {
		sort.Strings(problems)
		return fmt.Errorf("openapi.yaml has %d problem(s):\n  - %s", len(problems), strings.Join(problems, "\n  - "))
	}
	return nil
}

// checkProductInvariants is the spec-level half of CLAUDE.md §2. A field name that leaks
// an individual streak or the reliability score is a product bug even if it compiles, so
// it fails the build here rather than in review.
func (s *Spec) checkProductInvariants() []string {
	var problems []string

	bannedField := []struct{ substr, why string }{
		{"reliability_score", "the reliability score is never exposed to users (CLAUDE.md §6)"},
		{"reliability_band", "reliability bands are never exposed to users (CLAUDE.md §6)"},
		{"completion_rate", "personal completion rates reintroduce private guilt (CLAUDE.md §2 rule 3)"},
		{"follower", "there are no follower counts (CLAUDE.md §2 rule 5)"},
		{"public_profile", "there are no public profiles (CLAUDE.md §2 rule 5)"},
	}
	for _, sc := range s.Schemas {
		for _, p := range sc.Props {
			lower := strings.ToLower(p.Name)
			for _, b := range bannedField {
				if strings.Contains(lower, b.substr) {
					problems = append(problems, fmt.Sprintf("%s.%s: %s", sc.Name, p.Name, b.why))
				}
			}
			// Streaks are pod-level only.
			if strings.Contains(lower, "streak") && sc.Name != "Pod" {
				problems = append(problems, fmt.Sprintf("%s.%s: streaks are pod-level only — a streak field outside Pod reintroduces individual guilt (CLAUDE.md §2 rule 3)", sc.Name, p.Name))
			}
		}
	}

	// Nothing may describe a member's week as a failure.
	if st := s.schemaByName["MemberWeekState"]; st != nil {
		for _, v := range st.Enum {
			switch v {
			case "missed", "failed", "broken", "incomplete":
				problems = append(problems, fmt.Sprintf("MemberWeekState: %q is shaming vocabulary (CLAUDE.md §2 rule 1)", v))
			}
		}
	}

	// Every proof must carry its own expiry — ephemerality is a promise (rule 4).
	if pr := s.schemaByName["Proof"]; pr != nil && !pr.Required["expires_at"] {
		problems = append(problems, "Proof.expires_at must be required — proof is ephemeral (CLAUDE.md §2 rule 4)")
	}

	return problems
}

func checkTypeRef(s *Spec, where string, t *TypeRef) error {
	if t == nil {
		return fmt.Errorf("%s: property has no type", where)
	}
	if t.Ref != "" {
		if s.schemaByName[t.Ref] == nil {
			return fmt.Errorf("%s: unknown $ref %q", where, t.Ref)
		}
		return nil
	}
	switch t.Kind {
	case "string", "integer", "number", "boolean":
		return nil
	case "array", "map":
		return checkTypeRef(s, where+"[]", t.Elem)
	default:
		return fmt.Errorf("%s: unsupported type %q", where, t.Kind)
	}
}

// ----------------------------------------------------------------- name casing

func splitWords(s string) []string {
	var words []string
	cur := strings.Builder{}
	for _, r := range s {
		switch {
		case r == '_' || r == '-' || r == '.' || r == ' ' || r == '/':
			if cur.Len() > 0 {
				words = append(words, cur.String())
				cur.Reset()
			}
		default:
			cur.WriteRune(r)
		}
	}
	if cur.Len() > 0 {
		words = append(words, cur.String())
	}
	return words
}

var initialisms = map[string]string{"id": "ID", "url": "URL", "api": "API", "uri": "URI", "ms": "Ms"}

func pascal(s string) string {
	var b strings.Builder
	for _, w := range splitWords(s) {
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

func goPascal(s string) string {
	var b strings.Builder
	for _, w := range splitWords(s) {
		if up, ok := initialisms[strings.ToLower(w)]; ok && strings.ToLower(w) != "ms" {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

func camel(s string) string {
	p := pascal(s)
	if p == "" {
		return p
	}
	return strings.ToLower(p[:1]) + p[1:]
}

func screamingSnake(s string) string {
	var parts []string
	for _, w := range splitWords(s) {
		parts = append(parts, strings.ToUpper(w))
	}
	return strings.Join(parts, "_")
}

// docComment wraps text as a comment with the given prefix, one sentence-ish per line.
func docComment(indent, prefix, s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	var b strings.Builder
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimRight(line, " ")
		if line == "" {
			b.WriteString(indent + strings.TrimRight(prefix, " ") + "\n")
			continue
		}
		b.WriteString(indent + prefix + line + "\n")
	}
	return b.String()
}
