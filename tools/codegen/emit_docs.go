package main

import (
	"fmt"
	"sort"
	"strings"
)

func emitAPIDocs(s *Spec) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by tools/codegen from backend/openapi.yaml. DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&b, "# %s — v%s\n\n", s.Title, s.Version)
	b.WriteString(strings.TrimSpace(s.Description) + "\n\n")

	b.WriteString("## Servers\n\n| URL | |\n|---|---|\n")
	for _, srv := range s.Servers {
		fmt.Fprintf(&b, "| `%s` | %s |\n", srv.URL, srv.Description)
	}
	b.WriteString("\n")

	// Operation index, grouped by tag in the order the spec declares them.
	byTag := map[string][]opRef{}
	for _, p := range s.Paths {
		for _, op := range p.Operations {
			tag := "other"
			if len(op.Tags) > 0 {
				tag = op.Tags[0]
			}
			byTag[tag] = append(byTag[tag], opRef{path: p, op: op})
		}
	}
	tagOrder := make([]string, 0, len(byTag))
	for _, t := range s.Tags {
		if len(byTag[t.Name]) > 0 {
			tagOrder = append(tagOrder, t.Name)
		}
	}
	for tag := range byTag {
		if !contains(tagOrder, tag) {
			tagOrder = append(tagOrder, tag)
		}
	}

	b.WriteString("## Endpoints at a glance\n\n| Milestone | Method | Path | Operation | Auth |\n|---|---|---|---|---|\n")
	for _, tag := range tagOrder {
		for _, r := range byTag[tag] {
			auth := "bearer"
			if r.op.Public {
				auth = "public"
			}
			fmt.Fprintf(&b, "| %s | `%s` | `%s` | `%s` | %s |\n", r.op.Milestone, r.op.Method, r.path.Template, r.op.ID, auth)
		}
	}
	b.WriteString("\nOperations beyond **M1** are specified but answer `501 not_implemented_yet` until their milestone lands.\n\n")

	for _, tag := range tagOrder {
		desc := ""
		for _, t := range s.Tags {
			if t.Name == tag {
				desc = t.Description
			}
		}
		fmt.Fprintf(&b, "## %s\n\n", strings.ToUpper(tag[:1])+tag[1:])
		if desc != "" {
			b.WriteString(desc + "\n\n")
		}
		for _, r := range byTag[tag] {
			writeOperation(&b, s, r)
		}
	}

	b.WriteString("## Schemas\n\n")
	names := make([]string, 0, len(s.Schemas))
	for _, sc := range s.Schemas {
		names = append(names, sc.Name)
	}
	sort.Strings(names)
	for _, name := range names {
		writeSchema(&b, s, s.schemaByName[name])
	}
	return b.String()
}

type opRef struct {
	path *Path
	op   *Operation
}

func writeOperation(b *strings.Builder, s *Spec, r opRef) {
	op := r.op
	fmt.Fprintf(b, "### `%s %s` — %s\n\n", op.Method, r.path.Template, op.ID)
	fmt.Fprintf(b, "**%s**  \n", strings.TrimSuffix(op.Summary, "."))
	auth := "Requires a bearer access token."
	if op.Public {
		auth = "No authentication."
	}
	fmt.Fprintf(b, "Milestone %s · %s\n\n", op.Milestone, auth)
	if d := strings.TrimSpace(op.Description); d != "" {
		b.WriteString(d + "\n\n")
	}

	params := append(append([]*Param{}, r.path.Params...), op.Params...)
	if len(params) > 0 {
		b.WriteString("| Parameter | In | Required | Type |\n|---|---|---|---|\n")
		for _, p := range params {
			req := "no"
			if p.Required {
				req = "yes"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", p.Name, p.In, req, p.SchemaType)
		}
		b.WriteString("\n")
	}
	if op.RequestBody != "" {
		fmt.Fprintf(b, "Request body: [`%s`](#%s)\n\n", op.RequestBody, anchor(op.RequestBody))
	}
	b.WriteString("| Status | Body | |\n|---|---|---|\n")
	for _, resp := range op.Responses {
		body := "—"
		if resp.SchemaRef != "" {
			body = fmt.Sprintf("[`%s`](#%s)", resp.SchemaRef, anchor(resp.SchemaRef))
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", resp.Status, body, oneLine(resp.Description))
	}
	b.WriteString("\n")
}

func writeSchema(b *strings.Builder, s *Spec, sc *Schema) {
	fmt.Fprintf(b, "### %s\n\n", sc.Name)
	if d := strings.TrimSpace(sc.Description); d != "" {
		b.WriteString(d + "\n\n")
	}
	if len(sc.Enum) > 0 {
		b.WriteString("One of: ")
		for i, v := range sc.Enum {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "`%s`", v)
		}
		b.WriteString("\n\n")
		return
	}
	if len(sc.Props) == 0 {
		fmt.Fprintf(b, "Type: `%s`", sc.Type)
		if sc.Min != "" || sc.Max != "" {
			fmt.Fprintf(b, " (range %s–%s)", sc.Min, sc.Max)
		}
		b.WriteString("\n\n")
		return
	}
	b.WriteString("| Field | Type | Required | |\n|---|---|---|---|\n")
	for _, p := range sc.Props {
		req := ""
		if p.Required {
			req = "yes"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", p.Name, docType(s, p.Type), req, oneLine(p.Description))
	}
	b.WriteString("\n")
}

func docType(s *Spec, t *TypeRef) string {
	if t.Ref != "" {
		return fmt.Sprintf("[`%s`](#%s)", t.Ref, anchor(t.Ref))
	}
	switch t.Kind {
	case "array":
		return docType(s, t.Elem) + "[]"
	case "map":
		return "map<string, " + docType(s, t.Elem) + ">"
	default:
		if t.Format != "" {
			return fmt.Sprintf("`%s(%s)`", t.Kind, t.Format)
		}
		return "`" + t.Kind + "`"
	}
}

func anchor(name string) string {
	return strings.ToLower(name)
}

func oneLine(s string) string {
	s = strings.TrimSpace(strings.ReplaceAll(s, "\n", " "))
	for strings.Contains(s, "  ") {
		s = strings.ReplaceAll(s, "  ", " ")
	}
	return strings.ReplaceAll(s, "|", "\\|")
}

func contains(list []string, v string) bool {
	for _, item := range list {
		if item == v {
			return true
		}
	}
	return false
}
